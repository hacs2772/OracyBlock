/** 말투(어감) 알려 주기: 문장 끝을 보고 짐작해요 */
export function toneOf(line) {
  if (line.tone) return line.tone;
  const parts = line.ja.trim().split(/(?<=[。！？!?])/).filter((s) => s.trim());
  const last = (parts[parts.length - 1] || line.ja).trim();
  const core = last.replace(/[。！？!?…\s]+$/, '');
  const q = /[？?]$/.test(last);
  if (/でしょ(う)?$/.test(core)) return { mark: '↗', label: '확인하는 말투', note: '끝의 "~데쇼"는 "그렇죠? / 그치?" 하고 확인하는 말이에요.' };
  if (q && /の$/.test(core)) return { mark: '↗', label: '편하게 묻는 말투', note: '끝의 "~노?"는 반말로 편하게 물을 때 써요.' };
  if (q && /か$/.test(core)) return { mark: '↗', label: '정중하게 묻는 말투', note: '끝의 "~까?"는 존댓말 질문이에요.' };
  if (q) return { mark: '↗', label: '묻는 말투', note: '끝이 올라가면 질문이에요.' };
  if (/ねえ?$/.test(core)) return { mark: '〜', label: '공감을 구하는 말투', note: '끝의 "~네(ね)"는 "~지? / ~네" 하고 맞장구를 기다리는 말이에요.' };
  if (/よ$/.test(core)) return { mark: '!', label: '알려 주는 말투', note: '끝의 "~요(よ)"는 존댓말이 아니라 "~거든, ~야" 하고 알려 주는 말이에요.' };
  if (/[！!]$/.test(last)) return { mark: '!', label: '들뜬 말투', note: '힘이 들어간, 신나거나 놀란 말이에요.' };
  return { mark: '·', label: '차분한 말투', note: '' };
}

