/** 단어 튜플을 객체로: { key, say, variants, ko, mean } */
export function word(t) {
  const variants = t[0].split('|');
  return { key: variants[0], say: variants[0], variants, ko: t[1], mean: t[2] };
}

const asLine = ([ja, ko, mean]) => ({ ja, ko, mean });

TALKS.forEach((t, i) => {
  t.no = i + 1;
  t.code = String(i + 1).padStart(2, '0');
  t.turns.forEach((turn, j) => {
    turn.idx = j;
    if (turn.them) {
      turn.them.keys = turn.them.keys.map(word);
      if (turn.them.alt) turn.them.alt = turn.them.alt.map((a) => ({ ...a, mean: turn.them.mean, keys: a.keys.map(word) }));
    }
    if (turn.me) {
      turn.me = turn.me.map((o) => ({
        ...o,
        words: o.words.map(word),
        natural: asLine(o.natural),
        react: o.react ? { ...o.react, keys: [] } : null,
      }));
    }
  });
  // 대략 길이: 대사 하나에 25초쯤
  t.minutes = Math.max(3, Math.round((t.turns.length * 25) / 60));
});

export const THEM_LINES = TALKS.flatMap((t) => t.turns.filter((x) => x.them).map((x) => ({ line: x.them, talk: t })));

/** 에피소드에 나오는 핵심 단어 (자주 나오는 순) */
export function allKeyWords() {
  const map = new Map();
  for (const { line } of THEM_LINES) {
    for (const w of line.keys) {
      const cur = map.get(w.key);
      if (cur) cur.count++;
      else map.set(w.key, { ...w, count: 1 });
    }
  }
  return [...map.values()].sort((a, b) => b.count - a.count);
}

