/** 이 단어가 한국어랑 닮았으면 그 정보를, 아니면 null */
export function cognateOf(w) {
  for (const v of w.variants || [w.key]) {
    const c = COGNATE_BY_VARIANT.get(v);
    if (c) return c;
  }
  return null;
}

/** 오늘의 닮은 단어 (날마다 바뀌어요) */
export function dailyCognate(d = new Date()) {
  const day = Math.floor(new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime() / 864e5);
  return COGNATES[day % COGNATES.length];
}
